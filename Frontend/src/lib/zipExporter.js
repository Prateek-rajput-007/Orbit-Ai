/**
 * Exports files from a CodeArtifact as a downloadable .zip archive.
 * Uses dynamic import of JSZip to ensure bundle safety.
 *
 * @param {object} codeArtifact
 */
export async function downloadCodeArtifactZip(codeArtifact) {
  if (!codeArtifact || !Array.isArray(codeArtifact.files) || codeArtifact.files.length === 0) {
    return;
  }

  const safeTitle = (codeArtifact.title || "orbit-project")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 40) || "orbit-project";

  try {
    const JSZipModule = await import("jszip");
    const JSZip = JSZipModule.default || JSZipModule;
    const zip = new JSZip();

    for (const file of codeArtifact.files) {
      if (!file?.path) continue;
      const cleanPath = file.path.replace(/\\+/g, "/").replace(/^(\.\/|\/)+/, "");
      const content =
        typeof file.content === "string"
          ? file.content
          : file.content && typeof file.content === "object"
          ? JSON.stringify(file.content, null, 2)
          : String(file.content || "");
      zip.file(cleanPath, content);
    }

    // Add a README.md if not present
    if (!codeArtifact.files.some((f) => f.path?.toLowerCase() === "readme.md")) {
      const readmeContent = `# ${codeArtifact.title || "Orbit Generated Project"}

${codeArtifact.description || "Generated by Orbit AI Coding Assistant."}

## Files
${codeArtifact.files.map((f) => `- \`${f.path}\``).join("\n")}

## How to Run
${
  codeArtifact.previewType === "html"
    ? "Open `index.html` in any modern web browser or run a local static file server."
    : "Run the entry file using your preferred runtime (e.g. `node app.js` or `python main.py`)."
}
`;
      zip.file("README.md", readmeContent);
    }

    const blob = await zip.generateAsync({ type: "blob" });
    const blobUrl = window.URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = blobUrl;
    link.download = `${safeTitle}.zip`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    window.URL.revokeObjectURL(blobUrl);
    return true;
  } catch (error) {
    console.warn("JSZip export failed, falling back to raw download:", error);
    // Fallback: download entry file or bundled HTML directly
    const primaryFile =
      codeArtifact.files.find((f) => f.path === codeArtifact.entryFile) ||
      codeArtifact.files[0];
    if (primaryFile) {
      const rawContent =
        typeof primaryFile.content === "string"
          ? primaryFile.content
          : JSON.stringify(primaryFile.content, null, 2);
      const blob = new Blob([rawContent], { type: "text/plain;charset=utf-8" });
      const blobUrl = window.URL.createObjectURL(blob);
      const link = document.createElement("a");
      link.href = blobUrl;
      link.download = primaryFile.path.split("/").pop() || "index.html";
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      window.URL.revokeObjectURL(blobUrl);
    }
    return false;
  }
}
