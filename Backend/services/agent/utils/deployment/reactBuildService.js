import fs from "fs";
import path from "path";
import os from "os";
import { fork } from "child_process";
import { randomUUID } from "crypto";
import { fileURLToPath } from "url";
import { sanitizePath, isReactProject } from "../codeArtifact.js";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Concurrency guard to prevent CPU/memory exhaustion from overlapping builds
const MAX_CONCURRENT_BUILDS = 2;
let activeBuildCount = 0;

// Maximum input thresholds
const MAX_FILE_COUNT = 80;
const MAX_SINGLE_FILE_BYTES = 2 * 1024 * 1024; // 2 MB
const MAX_TOTAL_INPUT_BYTES = 10 * 1024 * 1024; // 10 MB
const MAX_OUTPUT_BUNDLE_BYTES = 15 * 1024 * 1024; // 15 MB

// Supported pre-bundled dependencies
export const SUPPORTED_DEPENDENCIES = [
    "react",
    "react-dom",
    "lucide-react",
    "clsx",
    "tailwind-merge",
    "framer-motion",
    "@tanstack/react-query",
];

// Untrusted configuration files that must never be executed
const UNTRUSTED_CONFIG_FILES = new Set([
    "vite.config.js",
    "vite.config.ts",
    "vite.config.mjs",
    "vite.config.cjs",
    "rollup.config.js",
    "webpack.config.js",
    "postcss.config.js",
    "postcss.config.cjs",
    "postcss.config.mjs",
    "tailwind.config.js",
    "tailwind.config.cjs",
    "tailwind.config.ts",
]);

/**
 * Dynamically resolves the Frontend/node_modules directory across test, dev, and production execution paths.
 *
 * @returns {string} Absolute path to Frontend/node_modules
 */
export function findFrontendNodeModules() {
    const candidates = [
        path.resolve(__dirname, "../../../../../Frontend/node_modules"),
        path.resolve(process.cwd(), "Frontend/node_modules"),
        path.resolve(process.cwd(), "../Frontend/node_modules"),
        path.resolve(process.cwd(), "../../Frontend/node_modules"),
    ];

    for (const c of candidates) {
        if (fs.existsSync(c)) {
            return c;
        }
    }

    throw new Error("Could not locate Frontend/node_modules directory for React production builder.");
}

/**
 * Validates the static build output files generated by Vite.
 *
 * @param {Array<{ path: string, content: string }>} files
 * @param {object} options
 * @returns {boolean}
 */
export function validateBuildOutput(files = [], options = {}) {
    if (!Array.isArray(files) || files.length === 0) {
        throw new Error("Build produced no output files.");
    }

    const indexHtml = files.find((f) => f.path.toLowerCase() === "index.html");
    if (!indexHtml || typeof indexHtml.content !== "string" || indexHtml.content.trim().length === 0) {
        throw new Error("Build output validation failed: dist/index.html is missing or empty.");
    }

    const hasJsAsset = files.some(
        (f) => f.path.toLowerCase().endsWith(".js") || f.path.toLowerCase().endsWith(".mjs")
    );
    if (!hasJsAsset) {
        throw new Error("Build output validation failed: no compiled JavaScript bundle was generated.");
    }

    const maxBytes = options.maxOutputBytes || MAX_OUTPUT_BUNDLE_BYTES;
    let totalBytes = 0;
    for (const f of files) {
        const size = Buffer.byteLength(f.content || "", "utf8");
        totalBytes += size;
    }

    if (totalBytes > maxBytes) {
        throw new Error(`Build output validation failed: total bundle size (${(totalBytes / 1024 / 1024).toFixed(2)} MB) exceeds maximum limit of ${(maxBytes / 1024 / 1024).toFixed(2)} MB.`);
    }

    return true;
}

/**
 * Strips internal machine paths and temp folder names from Vite error messages,
 * and converts unresolved import errors into clear actionable notices for unsupported dependencies.
 *
 * @param {string} rawMessage
 * @param {string} tmpDir
 * @returns {string}
 */
export function sanitizeBuildErrorMessage(rawMessage, tmpDir) {
    if (!rawMessage || typeof rawMessage !== "string") {
        return "Unknown build error occurred.";
    }

    // Check for unresolved import errors (unsupported dependencies)
    if (
        rawMessage.includes("Could not resolve") ||
        rawMessage.includes("UNRESOLVED_IMPORT") ||
        rawMessage.includes("failed to resolve import")
    ) {
        const match = rawMessage.match(/(?:Could not resolve|failed to resolve import)\s+["']([^"']+)["']/i);
        const missingPkg = match ? match[1] : null;
        if (missingPkg && !missingPkg.startsWith(".") && !missingPkg.startsWith("/")) {
            return `Unsupported dependency '${missingPkg}' requested. In isolated production builds, external dynamic package installation is disabled. Currently supported pre-bundled libraries are: ${SUPPORTED_DEPENDENCIES.join(", ")}. Please refactor to use supported libraries or native browser APIs.`;
        }
    }

    let sanitized = rawMessage;

    if (tmpDir) {
        // Strip out temp directory paths
        const normalizedTmp = tmpDir.replace(/\\/g, "/");
        sanitized = sanitized.replace(new RegExp(normalizedTmp.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "gi"), "");
        sanitized = sanitized.replace(new RegExp(tmpDir.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "gi"), "");
    }

    // Strip leading slashes from file paths left behind
    sanitized = sanitized.replace(/(\s|^)\/+(src\/)/g, "$1$2");

    return sanitized.trim();
}

/**
 * Validates input project files against security and size limits.
 *
 * @param {Array<{ path: string, content: string }>} files
 */
export function validateInputPayload(files = []) {
    if (!Array.isArray(files) || files.length === 0) {
        throw new Error("Cannot build React application: no files were provided.");
    }

    if (files.length > MAX_FILE_COUNT) {
        throw new Error(`Project exceeds maximum file count limit (${files.length} > ${MAX_FILE_COUNT} files).`);
    }

    let totalInputBytes = 0;
    for (const file of files) {
        if (!file || !file.path || typeof file.content !== "string") continue;
        const size = Buffer.byteLength(file.content, "utf8");
        if (size > MAX_SINGLE_FILE_BYTES) {
            throw new Error(`File "${file.path}" exceeds maximum size limit of 2 MB (${(size / 1024 / 1024).toFixed(2)} MB).`);
        }
        totalInputBytes += size;
    }

    if (totalInputBytes > MAX_TOTAL_INPUT_BYTES) {
        throw new Error(`Total project source code exceeds 10 MB limit (${(totalInputBytes / 1024 / 1024).toFixed(2)} MB).`);
    }
}

/**
 * Compiles a multi-file React project into production-ready static assets (HTML, CSS, JS)
 * using an isolated temporary directory and a dedicated child process with a memory and timeout ceiling.
 *
 * @param {Array<{ path: string, content: string }>} files Project files
 * @param {object} options
 * @param {string} [options.title] Application title
 * @param {number} [options.timeoutMs=30000] Maximum build time in milliseconds
 * @param {number} [options.maxOutputBytes=15728640] Maximum allowed dist bundle size (15 MB)
 * @returns {Promise<{ success: boolean, files?: Array<{ path: string, content: string }>, status?: string, error?: string, stats?: object }>}
 */
export async function buildReactProjectToStatic(files = [], options = {}) {
    const startTime = Date.now();
    const timeoutMs = options.timeoutMs || 30000;
    const maxOutputBytes = options.maxOutputBytes || MAX_OUTPUT_BUNDLE_BYTES;
    const title = options.title || "Orbit React Application";

    // Concurrency limit check
    if (activeBuildCount >= MAX_CONCURRENT_BUILDS) {
        return {
            success: false,
            status: "busy",
            error: `Build service is currently busy processing concurrent builds (${activeBuildCount}/${MAX_CONCURRENT_BUILDS}). Please retry shortly.`,
        };
    }

    activeBuildCount++;

    const buildId = randomUUID();
    const tmpDir = path.join(os.tmpdir(), `orbit-build-${buildId}`);
    let workerProcess = null;

    try {
        // Step 1: Validate input constraints
        validateInputPayload(files);

        const frontendNodeModules = findFrontendNodeModules();
        const vitePath = path.join(frontendNodeModules, "vite/dist/node/index.js");
        const reactPluginPath = path.join(frontendNodeModules, "@vitejs/plugin-react/dist/index.js");
        const workerScriptPath = path.join(__dirname, "reactBuildWorker.js");

        if (!fs.existsSync(vitePath)) {
            throw new Error(`Vite engine not found at: ${vitePath}`);
        }
        if (!fs.existsSync(reactPluginPath)) {
            throw new Error(`@vitejs/plugin-react not found at: ${reactPluginPath}`);
        }
        if (!fs.existsSync(workerScriptPath)) {
            throw new Error(`Build worker script not found at: ${workerScriptPath}`);
        }

        // Step 2: Create isolated build directory
        fs.mkdirSync(tmpDir, { recursive: true });

        // Step 3: Write project files safely into tmpDir
        let hasIndexHtml = false;
        let detectedEntry = null;

        for (const file of files) {
            if (!file || !file.path || typeof file.content !== "string") continue;

            // Security check: Block path traversal attempts
            const rawDest = path.resolve(tmpDir, file.path);
            if (!rawDest.startsWith(tmpDir) || file.path.startsWith("../") || file.path.includes("/../") || file.path.includes("\\..\\")) {
                throw new Error(`Security violation: Path traversal detected in "${file.path}".`);
            }

            const cleanRelPath = sanitizePath(file.path);
            const lowerPath = cleanRelPath.toLowerCase();
            const fileName = path.basename(lowerPath);

            // Policy: Untrusted configuration files are never written or executed
            if (UNTRUSTED_CONFIG_FILES.has(fileName)) {
                continue;
            }

            if (lowerPath === "index.html") {
                hasIndexHtml = true;
            }

            if (
                lowerPath === "src/main.jsx" ||
                lowerPath === "src/main.tsx" ||
                lowerPath === "src/index.jsx" ||
                lowerPath === "src/index.tsx"
            ) {
                detectedEntry = `/${cleanRelPath}`;
            } else if (!detectedEntry && (lowerPath === "src/app.jsx" || lowerPath === "src/app.tsx")) {
                detectedEntry = `/${cleanRelPath}`;
            }

            const absDest = path.resolve(tmpDir, cleanRelPath);
            fs.mkdirSync(path.dirname(absDest), { recursive: true });
            fs.writeFileSync(absDest, file.content, "utf8");
        }

        // Step 4: Ensure an entry point exists
        if (!detectedEntry) {
            const hasApp = fs.existsSync(path.join(tmpDir, "src/App.jsx")) || fs.existsSync(path.join(tmpDir, "App.jsx"));
            if (hasApp) {
                detectedEntry = "/src/main.jsx";
                const synthesizedMain = `import React from "react";
import { createRoot } from "react-dom/client";
import App from "${fs.existsSync(path.join(tmpDir, "src/App.jsx")) ? "./App.jsx" : "../App.jsx"}";

const container = document.getElementById("root") || document.body;
const root = createRoot(container);
root.render(<App />);`;
                fs.mkdirSync(path.join(tmpDir, "src"), { recursive: true });
                fs.writeFileSync(path.join(tmpDir, "src/main.jsx"), synthesizedMain, "utf8");
            } else {
                throw new Error("No React entry point found (expected src/main.jsx, src/index.jsx, or src/App.jsx).");
            }
        }

        // Step 5: Ensure root index.html exists and references the entry module script
        const indexHtmlPath = path.join(tmpDir, "index.html");
        if (!hasIndexHtml || !fs.existsSync(indexHtmlPath)) {
            const defaultHtml = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${title}</title>
  <script src="https://cdn.tailwindcss.com"></script>
</head>
<body class="bg-slate-900 text-slate-100 min-h-screen">
  <div id="root"></div>
  <script type="module" src="${detectedEntry}"></script>
</body>
</html>`;
            fs.writeFileSync(indexHtmlPath, defaultHtml, "utf8");
        } else {
            let existingHtml = fs.readFileSync(indexHtmlPath, "utf8");
            const hasScript = existingHtml.includes(`src="${detectedEntry}"`) ||
                existingHtml.includes(`src=".${detectedEntry}"`) ||
                /type=["']module["']/i.test(existingHtml);

            if (!hasScript) {
                const scriptTag = `  <script type="module" src="${detectedEntry}"></script>\n`;
                if (existingHtml.includes("</body>")) {
                    existingHtml = existingHtml.replace("</body>", `${scriptTag}</body>`);
                } else {
                    existingHtml += `\n${scriptTag}`;
                }
            }

            const hasTailwind = existingHtml.includes("tailwindcss") ||
                existingHtml.includes("cdn.tailwindcss.com") ||
                files.some((f) => f.path.endsWith(".css") && (f.content.includes("@import") || f.content.includes("tailwindcss")));

            if (!hasTailwind) {
                const tailwindTag = `  <script src="https://cdn.tailwindcss.com"></script>\n`;
                if (existingHtml.includes("</head>")) {
                    existingHtml = existingHtml.replace("</head>", `${tailwindTag}</head>`);
                } else if (existingHtml.includes("<html>")) {
                    existingHtml = existingHtml.replace("<html>", `<html><head>${tailwindTag}</head>`);
                } else {
                    existingHtml = `${tailwindTag}${existingHtml}`;
                }
            }

            fs.writeFileSync(indexHtmlPath, existingHtml, "utf8");
        }

        // Step 6: Configure aliases for supported runtime dependencies
        const aliases = [
            { find: /^react\/jsx-runtime$/, replacement: path.join(frontendNodeModules, "react/jsx-runtime.js") },
            { find: /^react\/jsx-dev-runtime$/, replacement: path.join(frontendNodeModules, "react/jsx-dev-runtime.js") },
            { find: /^react-dom\/client$/, replacement: path.join(frontendNodeModules, "react-dom/client.js") },
            { find: /^react-dom$/, replacement: path.join(frontendNodeModules, "react-dom/index.js") },
            { find: /^react$/, replacement: path.join(frontendNodeModules, "react/index.js") },
            { find: /^lucide-react$/, replacement: path.join(frontendNodeModules, "lucide-react/dist/esm/lucide-react.mjs") },
            { find: /^clsx$/, replacement: path.join(frontendNodeModules, "clsx/dist/clsx.mjs") },
            { find: /^tailwind-merge$/, replacement: path.join(frontendNodeModules, "tailwind-merge/dist/bundle-mjs.mjs") },
            { find: /^framer-motion$/, replacement: path.join(frontendNodeModules, "framer-motion/dist/es/index.mjs") },
            { find: /^@tanstack\/react-query$/, replacement: path.join(frontendNodeModules, "@tanstack/react-query/build/modern/index.js") },
        ];

        // Step 7: Spawn isolated child worker process with stripped environment (zero host secrets)
        const sanitizedEnv = {
            NODE_ENV: "production",
            PATH: process.env.PATH || "",
            TEMP: os.tmpdir(),
            TMP: os.tmpdir(),
            SYSTEMROOT: process.env.SYSTEMROOT || "",
            APPDATA: process.env.APPDATA || "",
            HOMEPATH: process.env.HOMEPATH || "",
            USERPROFILE: process.env.USERPROFILE || "",
        };

        const workerResult = await new Promise((resolve, reject) => {
            let settled = false;
            let timeoutHandle = null;

            workerProcess = fork(workerScriptPath, [], {
                execArgv: ["--max-old-space-size=512"], // V8 memory limit ceiling
                env: sanitizedEnv,
                stdio: ["pipe", "pipe", "pipe", "ipc"],
            });

            timeoutHandle = setTimeout(() => {
                if (!settled) {
                    settled = true;
                    try {
                        workerProcess.kill("SIGKILL");
                    } catch {}
                    reject(new Error(`React production build timed out after ${Math.round(timeoutMs / 1000)}s`));
                }
            }, timeoutMs);

            workerProcess.on("message", (response) => {
                if (!settled) {
                    settled = true;
                    clearTimeout(timeoutHandle);
                    if (response.success) {
                        resolve();
                    } else {
                        reject(new Error(response.error || "Worker compilation error"));
                    }
                }
            });

            workerProcess.on("error", (procErr) => {
                if (!settled) {
                    settled = true;
                    clearTimeout(timeoutHandle);
                    reject(procErr);
                }
            });

            workerProcess.on("exit", (code, signal) => {
                if (!settled) {
                    settled = true;
                    clearTimeout(timeoutHandle);
                    reject(new Error(`Build process exited unexpectedly with code ${code} and signal ${signal}`));
                }
            });

            workerProcess.send({
                type: "build",
                tmpDir,
                fModules: frontendNodeModules,
            });
        });

        // Step 8: Read and collect compiled static assets from dist/
        const distDir = path.join(tmpDir, "dist");
        if (!fs.existsSync(distDir)) {
            throw new Error("Build failed: Vite did not create a dist directory.");
        }

        const outputFiles = [];

        function readDirRecursive(currentDir, baseRelative = "") {
            const entries = fs.readdirSync(currentDir, { withFileTypes: true });
            for (const entry of entries) {
                const fullPath = path.join(currentDir, entry.name);
                const relPath = baseRelative ? `${baseRelative}/${entry.name}` : entry.name;

                if (entry.isDirectory()) {
                    readDirRecursive(fullPath, relPath);
                } else if (entry.isFile()) {
                    const content = fs.readFileSync(fullPath, "utf8");
                    outputFiles.push({
                        path: relPath.replace(/\\/g, "/"),
                        content,
                    });
                }
            }
        }

        readDirRecursive(distDir);

        // Step 9: Validate the generated build output
        validateBuildOutput(outputFiles, { maxOutputBytes });

        const buildDuration = Date.now() - startTime;
        let totalSize = 0;
        for (const f of outputFiles) {
            totalSize += Buffer.byteLength(f.content, "utf8");
        }

        return {
            success: true,
            status: "built",
            files: outputFiles,
            provider: "Vite",
            stats: {
                fileCount: outputFiles.length,
                totalSize,
                buildTimeMs: buildDuration,
            },
        };
    } catch (err) {
        const buildDuration = Date.now() - startTime;
        const cleanError = sanitizeBuildErrorMessage(err.message || String(err), tmpDir);

        console.error(`[ReactBuildService] Build error (${buildDuration}ms):`, cleanError);

        return {
            success: false,
            status: "build_failed",
            error: `React production build failed: ${cleanError}`,
            logs: err.stack ? sanitizeBuildErrorMessage(err.stack, tmpDir) : undefined,
        };
    } finally {
        activeBuildCount = Math.max(0, activeBuildCount - 1);

        // Ensure child process is killed if still running
        if (workerProcess && !workerProcess.killed) {
            try {
                workerProcess.kill("SIGKILL");
            } catch {}
        }

        // Guaranteed cleanup of the temporary build directory
        try {
            if (fs.existsSync(tmpDir)) {
                fs.rmSync(tmpDir, { recursive: true, force: true });
            }
        } catch (cleanupErr) {
            console.warn(`[ReactBuildService] Failed to remove temp directory ${tmpDir}:`, cleanupErr.message);
        }
    }
}
