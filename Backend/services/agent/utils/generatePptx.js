import pptxgen from "pptxgenjs";

const sanitizeFileName = (title = "presentation") => {
    return title
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-+|-+$/g, "")
        .slice(0, 40) || "presentation";
};

/**
 * Compiles a structured slide deck JSON into a downloadable .pptx presentation.
 * Uses a professional 16:9 widescreen executive template with presenter notes.
 *
 * @param {object} deckData - Structured slides data { deckTitle, slides: [...] }
 * @returns {Promise<{ fileName: string, dataUrl: string, deckTitle: string }>}
 */
export const generatePptxFile = async (deckData = {}) => {
    const pptx = new pptxgen();
    pptx.layout = "LAYOUT_16x9";
    pptx.title = deckData.deckTitle || "Orbit Presentation";
    pptx.author = "Orbit AI";

    const slides = Array.isArray(deckData.slides) ? deckData.slides : [];
    const deckTitle = deckData.deckTitle || "Presentation Deck";

    // Palette: Executive Modern Theme
    const colors = {
        primaryDark: "0F172A", // Slate 900
        primaryLight: "F8FAFC", // Slate 50
        accentAmber: "F59E0B",  // Orbit Signature Amber
        textDark: "1E293B",     // Slate 800
        textMuted: "64748B",    // Slate 500
        cardBg: "F1F5F9",       // Slate 100
    };

    slides.forEach((slideItem, index) => {
        const slide = pptx.addSlide();
        const isTitleSlide = index === 0;

        if (isTitleSlide) {
            // Dark Title Slide
            slide.background = { color: colors.primaryDark };

            // Accent bar
            slide.addShape(pptx.ShapeType.rect, {
                x: 0.8,
                y: 1.5,
                w: 0.15,
                h: 2.2,
                fill: { color: colors.accentAmber },
            });

            // Deck Title
            slide.addText(slideItem.title || deckTitle, {
                x: 1.2,
                y: 1.5,
                w: 10.5,
                h: 1.5,
                fontSize: 40,
                bold: true,
                color: colors.primaryLight,
                fontFace: "Arial",
                valign: "top",
            });

            // Subtitle
            const subtitleText = slideItem.subtitle || (slideItem.bullets && slideItem.bullets[0]) || "Created with Orbit AI";
            slide.addText(subtitleText, {
                x: 1.2,
                y: 3.2,
                w: 10.5,
                h: 0.8,
                fontSize: 20,
                color: colors.accentAmber,
                fontFace: "Arial",
            });

            // Footer branding
            slide.addText("Generated by Orbit", {
                x: 1.2,
                y: 6.2,
                w: 5.0,
                h: 0.4,
                fontSize: 11,
                color: colors.textMuted,
            });
        } else {
            // Light Content Slide
            slide.background = { color: "FFFFFF" };

            // Header Title
            slide.addText(slideItem.title || `Slide ${index + 1}`, {
                x: 0.8,
                y: 0.6,
                w: 11.5,
                h: 0.7,
                fontSize: 24,
                bold: true,
                color: colors.primaryDark,
                fontFace: "Arial",
            });

            // Accent underline
            slide.addShape(pptx.ShapeType.line, {
                x: 0.8,
                y: 1.35,
                w: 11.7,
                h: 0,
                line: { color: colors.accentAmber, width: 2 },
            });

            // Slide Subtitle if present
            if (slideItem.subtitle) {
                slide.addText(slideItem.subtitle, {
                    x: 0.8,
                    y: 1.45,
                    w: 11.5,
                    h: 0.4,
                    fontSize: 13,
                    color: colors.textMuted,
                    italic: true,
                });
            }

            // Bullet points
            const bullets = Array.isArray(slideItem.bullets) ? slideItem.bullets : [];
            if (bullets.length > 0) {
                const bulletStartY = slideItem.subtitle ? 2.0 : 1.7;
                const bulletItems = bullets.map((bullet) => ({
                    text: bullet,
                    options: {
                        bullet: { type: "bullet", color: colors.accentAmber },
                        fontSize: 16,
                        color: colors.textDark,
                        lineSpacing: 26,
                        paraSpaceAfter: 14,
                        fontFace: "Arial",
                    },
                }));

                slide.addText(bulletItems, {
                    x: 0.8,
                    y: bulletStartY,
                    w: 11.5,
                    h: 4.8,
                    valign: "top",
                });
            }

            // Slide Number in footer
            slide.addText(`${index + 1}`, {
                x: 12.0,
                y: 6.8,
                w: 0.8,
                h: 0.3,
                fontSize: 10,
                color: colors.textMuted,
                align: "right",
            });
        }

        // Attach presenter speaker notes to PowerPoint slide
        if (slideItem.speakerNotes) {
            slide.addNotes(slideItem.speakerNotes);
        }
    });

    const base64Content = await pptx.write({ outputType: "base64" });
    const fileName = `${sanitizeFileName(deckTitle)}.pptx`;

    return {
        fileName,
        dataUrl: `data:application/vnd.openxmlformats-officedocument.presentationml.presentation;base64,${base64Content}`,
        deckTitle,
    };
};
